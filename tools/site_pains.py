def section(h2, lead, items, cls):
    cards = ''.join(
        f'<article class="pain reveal"><div class="pain-top"><span class="pain-ic">{I[k]}</span><span class="pain-no">{i:02d}</span></div>'
        f'<h3>{E(q)}</h3><div class="pain-sol"><span class="pain-lbl"><i>{CHECK}</i>Решение</span><p>{E(a)}</p></div></article>'
        for i, (k, q, a) in enumerate(items, 1))
    return (f'<section class="{cls}" id="trudnosti">\n  <div class="wrap">\n    <div class="sec-head">\n'
            f'      <div><span class="label reveal"><i class="sq"></i>Знаем ваши трудности</span><h2 class="h2 reveal d1">{h2}</h2></div>\n'
            f'      <p class="lead reveal d2" style="max-width:440px">{E(lead)}</p>\n    </div>\n'
            f'    <div class="pain-grid">{cards}</div>\n'
            f'    <div class="pain-ft reveal"><div><b>Узнали свою ситуацию?</b><span>Расскажите — подскажем, как решить, бесплатно.</span></div>'
            f'<a class="btn btn-ink" href="#lead">Разобрать мою задачу {ARROW}</a></div>\n  </div>\n</section>\n')


def run():
    for page, (h2, lead, items) in PAGES.items():
        p = os.path.join(ROOT, page)
        s = open(p, encoding='utf-8').read()
        if 'id="trudnosti"' in s:
            a = s.rindex('<section', 0, s.index('id="trudnosti"'))
            b = s.index('</section>', a) + len('</section>\n')
            s = s[:a].rstrip('\n') + '\n' + s[b:].lstrip('\n')
        hero_end = s.index('</section>', s.index('<section class="hero')) + len('</section>\n')
        rest = s[hero_end:].lstrip('\n')
        if rest.startswith('<div class="ticker'):  # бегущую строку оставляем сразу под первым экраном
            hero_end = s.index('\n', s.index('<div class="ticker', hero_end)) + 1
        k = s.index('<section class="', hero_end)
        nxt_cls = s[k + 16:s.index('"', k + 16)]
        cls = 'sec' if 'white' in nxt_cls.split() else 'sec white'
        s = s[:hero_end] + '\n' + section(h2, lead, items, cls) + s[hero_end:]
        open(p, 'w', encoding='utf-8', newline='').write(s)
        print('ok', page, len(items), cls)


if __name__ == '__main__':
    run()
